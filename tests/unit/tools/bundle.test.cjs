"use strict";

const assert = require("node:assert/strict");
const test = require("node:test");
const vm = require("node:vm");
const { jxaWorld } = require("../runtime/fake-jxa.cjs");
const { box } = require("../runtime/fake-foundation.cjs");

/*
 * The artifact: the same text from the same source, carrying its licence, and
 * loadable with nothing from Node or macOS in reach.
 */

const load = () => import("../../../tools/bundle.mjs");
// The global the artifact defines, which a native harness reaches into.
const ARTIFACT = "__TermAtTarget";

async function loaded() {
    const { renderRelease } = await load();
    const context = vm.createContext({});

    vm.runInContext(await renderRelease(), context);

    return context;
}

test("the same source renders the same artifact", async () => {
    const { renderRelease } = await load();

    assert.equal(await renderRelease(), await renderRelease());
});

test("the artifact opens with its name, version, AGPL notice and where its source is", async () => {
    const { renderRelease } = await load();
    const artifact = await renderRelease();
    const { version } = require("../../../package.json");

    assert.ok(artifact.startsWith(`/*\n * Term At Target ${version}\n * https://github.com/resoltico/TermAtTarget\n`));
    assert.match(artifact, /\n \* SPDX-License-Identifier: AGPL-3\.0-only\n/u);
    assert.match(artifact, /\n \* Copyright \(c\) 2026 Ervins Strauhmanis\n/u);
    assert.match(artifact, /GNU Affero General\n \* Public License, version 3 only\. It comes WITHOUT ANY WARRANTY\./u);
    assert.ok(artifact.includes(` * Corresponding Source: https://github.com/resoltico/TermAtTarget/tree/v${version}\n`));
    assert.match(artifact, / \* with nothing selected\. Requires macOS 12\.3 or later\.\n \*\/\n\n/u);
});

test("every comment is stripped but the header and the Unicode notice, which comes last before run()", async () => {
    const { renderRelease } = await load();
    const artifact = await renderRelease();
    const notice = artifact.indexOf("/*!\n * Term At Target's Unicode tables are derived from Unicode");

    assert.equal(artifact.split("/*").length - 1, 2, "the header and the notice, nothing else");
    assert.ok(notice > 0);
    assert.match(artifact.slice(notice), /UNICODE LICENSE V3[\s\S]*\*\/\nfunction run\(input, parameters\) \{\n {4}return __TermAtTarget\.run\(input\);\n\}\n$/u);
    assert.doesNotMatch(artifact, /Generated by tools\/unicode/u, "the generator's own comment is gone");
});

test("the code is minified but its names are kept", async () => {
    const { renderRelease } = await load();
    const artifact = await renderRelease();
    const code = artifact.slice(artifact.indexOf("*/\n\n") + 4, artifact.indexOf("/*!"));

    assert.ok(code.split("\n").length < 20, "whitespace is removed");
    assert.match(code, /function folderDestination\(\{path,via\},settings,files,request\)/u);
});

test("nothing in it is meant to be edited: there is no configuration to inline", async () => {
    // Settings are saved by the action itself, so every installed copy is
    // byte-identical to the release and its checksum always verifies.
    const { renderRelease } = await load();
    const artifact = await renderRelease();

    assert.match(artifact, /\n \* Generated file; do not edit\./u);
    assert.doesNotMatch(artifact, /CONFIG|#config|#metadata/u);
});

test("loading it needs no Node and no macOS, and declares run() for osascript", async () => {
    const context = await loaded();

    assert.equal(typeof context.run, "function");
    assert.deepEqual(Object.keys(context[ARTIFACT]), ["run"]);
    assert.equal(context.require, undefined);
    assert.equal(context.process, undefined);
    assert.equal(context.ObjC, undefined);
});

test("the manifest is the artifact's SHA-256 and its published name", async () => {
    const { renderManifest, digestOf } = await load();

    assert.equal(digestOf("abc"), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
    assert.equal(renderManifest("abc"), `${digestOf("abc")}  Term-At-Target.jxa\n`);
});

test("the production bundle rejects a source module absent from esbuild's inputs", async () => {
    const { assertBundled } = await load();
    const entry = "src/runtime/entry.js";
    const omitted = "src/core/orphan.js";

    assert.throws(() => assertBundled([entry, omitted], [entry]),
        /^Error: Source modules the bundle does not reach: src\/core\/orphan\.js$/u);
});

function launchBridge(world, folder) {
    const { $: ns, ObjC } = world.globals;
    const bundleIds = [];
    const task = { launchAndReturnError: () => true, running: false, terminationStatus: 0 };

    Object.assign(ns, {
        NSWorkspace: { sharedWorkspace: {
            URLForApplicationWithBundleIdentifier(id) {
                bundleIds.push(id);
                return box("installed");
            }
        } },
        NSTask: { alloc: { init: task } },
        NSFileTypeDirectory: "Directory",
        NSFileTypeSymbolicLink: "SymbolicLink",
        NSFileTypeRegular: "Regular"
    });
    Object.assign(ns.NSFileManager.defaultManager, {
        attributesOfItemAtPathError: () => ({ isNil: () => false, objectForKey: () => box("Directory") }),
        isExecutableFileAtPath: () => true
    });
    ns.NSUserDefaults.standardUserDefaults.persistentDomainForName = () => box({ terminal: "ghostty", folder });
    ObjC.deepUnwrap = (value) => value.data;
    ObjC.unwrap = (value) => value?.data ?? value;

    return { bundleIds, task };
}

async function hostForArtifact(configure) {
    const { renderRelease } = await load();
    const { globals, seen } = jxaWorld();
    const context = vm.createContext(globals);
    const { currentApplication } = globals.Application;

    globals.Application.currentApplication = () => Object.assign(currentApplication(), {
        displayAlert: (...args) => configure.alerts.push(args)
    });
    vm.runInContext(await renderRelease(), context);

    return { context, globals, seen };
}

test("the production run sends the configured folder to the saved app", async () => {
    const world = await hostForArtifact({ alerts: [] });

    for (const [folder, expected] of [["inside", "/work"], ["parent", "/"]]) {
        const { task, bundleIds } = launchBridge(world, folder);

        assert.deepEqual([...world.context.run(["/work"])], []);
        assert.deepEqual(bundleIds, ["com.mitchellh.ghostty"]);
        assert.deepEqual([...task.arguments], ["-b", "com.mitchellh.ghostty", expected]);
    }
});

test("the production run refuses multiple items before reading settings", async () => {
    const alerts = [];
    const { context, seen } = await hostForArtifact({ alerts });

    assert.deepEqual([...context.run([["/a", "/b"], { source: "", ignoresInput: false }])], []);
    assert.equal(alerts.length, 1);
    assert.equal(alerts[0][0], "Select one item at a time");
    assert.deepEqual(seen.domains, []);
});

test("the native entry exports the adapters in the test bundle", async () => {
    const { renderBundle } = await load();
    const { code } = await renderBundle("tests/integration/entry.cjs");
    const context = vm.createContext({});

    vm.runInContext(code, context);
    assert.deepEqual(Object.keys(context[ARTIFACT]).sort(), [
        "createFailureReport", "createFoundation", "createMacHost", "createPreferences",
        "createQuestions", "execute", "presentName", "readSelection", "supervise", "validateDirectory"
    ]);
    assert.equal(typeof context[ARTIFACT].execute, "function");
});
